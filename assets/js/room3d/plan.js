  function lecture() {
    var items = [{ type: 'screen', x: 0.9, y: 4.7, w: 3, rot: 0 }, { type: 'projector', x: 9.2, y: 4.67, rot: 180 }];
    var seats = [1.8, 2.4, 3.0, 3.6, 5.7, 6.3, 6.9, 7.5];
    for (var k = 0; k < 7; k++) for (var s = 0; s < seats.length; s++) items.push(chair(2.6 + 0.9 * k, seats[s], 180));
    return items;
  }
  // Большой стол 7,8 × 1,4 м вдоль окон, 13 стульев с каждой стороны и по одному в торцах
  function bigTable() {
    var items = [{ type: 'table', x: 5.7, y: 2.3, w: 7.8, d: 1.4, rot: 0 }];
    for (var k = 0; k < 13; k++) items.push(chair(2.1 + 0.6 * k, 1.15, 90), chair(2.1 + 0.6 * k, 3.45, 270));
    items.push(chair(1.35, 2.3, 0), chair(10.05, 2.3, 180));
    return items;
  }
  // Мастер-класс: шесть островов по два стола 1,2 × 0,6 и четыре стула; стол ведущего и флипчарт у стены с часами
